import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "..");
const packageDirs = ["receipt-river", "session-mycology", "fork-tax"];

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));
const escapeCljsString = (value) => JSON.stringify(value);

function filesUnder(root) {
  const found = [];
  for (const name of readdirSync(root).sort()) {
    const path = join(root, name);
    if (statSync(path).isDirectory()) {
      found.push(...filesUnder(path));
    } else if (name.endsWith(".edn")) {
      found.push(path);
    }
  }
  return found;
}

function schemaIdentity(edn, path) {
  const id = edn.match(/:schema\/id\s+(:[^\s}\]]+)/)?.[1];
  const version = Number(edn.match(/:schema\/version\s+(\d+)/)?.[1]);
  const status = edn.match(/:schema\/status\s+(:[^\s}\]]+)/)?.[1];
  if (!id || !Number.isInteger(version) || !status) {
    throw new Error(`Incomplete schema identity in ${relative(repoRoot, path)}`);
  }
  return { id, version, status };
}

function packageNamespace(dir) {
  return dir.replaceAll("-", "_");
}

const packages = packageDirs.map((dir) => {
  const root = join(repoRoot, "packages", dir);
  const packageJson = readJson(join(root, "package.json"));
  const schemas = filesUnder(join(root, "resources", "schemas")).map((path) => {
    const edn = readFileSync(path, "utf8").trim();
    return { path, edn, ...schemaIdentity(edn, path) };
  });
  const current = schemas.filter(({ status }) => status === ":current");
  if (current.length === 0) {
    throw new Error(`${packageJson.name} has no current schemas`);
  }
  const nsDir = packageNamespace(dir);
  const generatedPath = join(
    root,
    "src",
    "cljs",
    "eta_mu",
    nsDir,
    "generated",
    "registry.cljs",
  );
  mkdirSync(dirname(generatedPath), { recursive: true });
  const source = `(ns eta-mu.${dir}.generated.registry
  "Generated from resources/schemas by scripts/generate-ledger-metadata.mjs."
  (:require [cljs.reader :as reader]))

(def package-name ${escapeCljsString(packageJson.name)})
(def package-version ${escapeCljsString(packageJson.version)})

(def schema-documents
  (mapv reader/read-string
        [${schemas.map(({ edn }) => escapeCljsString(edn)).join("\n         ")}]))

(def schemas
  (into {}
        (map (fn [schema]
               [[(:schema/id schema) (:schema/version schema)] schema]))
        schema-documents))

(def schemas-by-id
  (group-by :schema/id schema-documents))

(def current-versions
  (into {}
        (comp (filter #(= :current (:schema/status %)))
              (map (juxt :schema/id :schema/version)))
        schema-documents))
`;
  writeFileSync(generatedPath, source);
  return { dir, root, packageJson, schemas, current };
});

const etaMuPackage = readJson(join(repoRoot, "packages", "eta-mu", "package.json"));
const gitSha = execFileSync("git", ["rev-parse", "HEAD"], {
  cwd: repoRoot,
  encoding: "utf8",
}).trim();
const builtAt = execFileSync("git", ["show", "-s", "--format=%cI", "HEAD"], {
  cwd: repoRoot,
  encoding: "utf8",
}).trim();

const componentsEdn = packages
  .map(({ packageJson }) => `${escapeCljsString(packageJson.name)} ${escapeCljsString(packageJson.version)}`)
  .join("\n  ");
const schemasEdn = packages
  .flatMap(({ current }) => current)
  .map(({ id, version }) => `${id} ${version}`)
  .join("\n  ");
const manifestEdn = `{:eta-mu/version ${escapeCljsString(etaMuPackage.version)}
 :components
 {${componentsEdn}}
 :schemas
 {${schemasEdn}}
 :build
 {:git/sha ${escapeCljsString(gitSha)}
  :built-at ${escapeCljsString(builtAt)}}}`;

mkdirSync(join(repoRoot, "packages", "eta-mu", "resources"), { recursive: true });
writeFileSync(
  join(repoRoot, "packages", "eta-mu", "resources", "component-manifest.edn"),
  `${manifestEdn}\n`,
);
mkdirSync(
  join(repoRoot, "packages", "eta-mu", "src", "cljs", "eta_mu", "generated"),
  { recursive: true },
);
writeFileSync(
  join(
    repoRoot,
    "packages",
    "eta-mu",
    "src",
    "cljs",
    "eta_mu",
    "generated",
    "component_manifest.cljs",
  ),
  `(ns eta-mu.generated.component-manifest
  "Generated by scripts/generate-ledger-metadata.mjs."
  (:require [cljs.reader :as reader]))

(def manifest
  (reader/read-string ${escapeCljsString(manifestEdn)}))
`,
);
